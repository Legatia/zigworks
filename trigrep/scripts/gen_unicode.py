#!/usr/bin/env python3
"""Generates src/unicode_tables.zig from Python's unicodedata.

Run: python3 scripts/gen_unicode.py > src/unicode_tables.zig
"""
import sys
import unicodedata

MAX = 0x10FFFF


def ranges(pred, start=0x80):
    out, lo = [], None
    for cp in range(start, MAX + 2):
        ok = cp <= MAX and not (0xD800 <= cp <= 0xDFFF) and pred(cp)
        if ok and lo is None:
            lo = cp
        elif not ok and lo is not None:
            out.append((lo, cp - 1))
            lo = None
    return out


def cat(cp):
    return unicodedata.category(chr(cp))


# Same definitions as ripgrep's regex crate (UTS #18 "simple" level):
# \w = Alphabetic + Mark + Decimal_Number + Connector_Punctuation + Join_Control.
# Alphabetic is approximated by letters (L*), letter numbers (Nl) and Other_Alphabetic
# marks, which the M* categories cover.
word = ranges(lambda c: cat(c)[0] in "LM" or cat(c) in ("Nd", "Nl", "Pc") or c in (0x200C, 0x200D))
digit = ranges(lambda c: cat(c) == "Nd")
WHITE_SPACE = {0x85, 0xA0, 0x1680, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000} | set(range(0x2000, 0x200B))
space = ranges(lambda c: c in WHITE_SPACE)

# Simple case folding orbits: code points that are the same letter ignoring case.
orbits = {}
for cp in range(0, MAX + 1):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    ch = chr(cp)
    for other in (ch.lower(), ch.upper(), ch.casefold(), ch.title()):
        if len(other) == 1 and other != ch:
            a, b = cp, ord(other)
            ga, gb = orbits.get(a, {a}), orbits.get(b, {b})
            g = ga | gb
            for x in g:
                orbits[x] = g
pairs = sorted({(a, b) for a, g in orbits.items() for b in g if a != b and (a >= 0x80 or b >= 0x80)})

w = sys.stdout.write
w("//! Generated by scripts/gen_unicode.py from Unicode %s (Python unicodedata). Do not edit.\n\n" % unicodedata.unidata_version)
for name, rs, doc in (("word", word, r"\w"), ("digit", digit, r"\d"), ("space", space, r"\s")):
    w("/// Non-ASCII code point ranges for %s.\n" % doc)
    w("pub const %s = [_][2]u21{\n" % name)
    for lo, hi in rs:
        w("    .{ 0x%X, 0x%X },\n" % (lo, hi))
    w("};\n\n")
w("/// Simple case folding, both directions: (a, b) means b is a case variant of a.\n")
w("/// Sorted by a. Only pairs where one side is non-ASCII.\n")
w("pub const fold = [_][2]u21{\n")
for a, b in pairs:
    w("    .{ 0x%X, 0x%X },\n" % (a, b))
w("};\n")
